// Generates src/theme/tokens.generated.ts from the Android theme (DESIGN 18.2): every color theme's light and dark
// Material 3 scheme (Color.kt, PresetColors.kt) and the fixed status colors (StatusColors.kt), in the order
// Settings offers them (Theme.kt). Run with `npm run gen`; CI checks the output is current.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const THEME_DIR = new URL('../../app/src/main/kotlin/com/parcha/spoilnot/core/designsystem/theme/', import.meta.url);
const OUT = new URL('../src/theme/tokens.generated.ts', import.meta.url);

export type Scheme = Record<string, string>;

/** `internal val Name = lightColorScheme(role = Color(0xFFRRGGBB), ...)` blocks, by val name. */
export function parseSchemes(kotlin: string): Record<string, Scheme> {
  const schemes: Record<string, Scheme> = {};
  const block = /val (\w+) =\s*(?:light|dark)ColorScheme\(([\s\S]*?)\n\s*\)/g;
  for (const [, name, body] of kotlin.matchAll(block)) {
    const scheme: Scheme = {};
    for (const [, role, argb] of body!.matchAll(/(\w+) = Color\(0x[0-9A-Fa-f]{2}([0-9A-Fa-f]{6})\)/g)) {
      scheme[role!] = `#${argb!.toLowerCase()}`;
    }
    schemes[name!] = scheme;
  }
  return schemes;
}

/** The ColorTheme entries with a fixed scheme, in order: id and the light and dark val names. */
export function parseThemes(themeKt: string): { id: string; light: string; dark: string }[] {
  const ids = new Map([...themeKt.matchAll(/^\s{4}(\w+)\("([a-z_]+)"\)/gm)].map(([, entry, id]) => [entry!, id!]));
  return [...themeKt.matchAll(/(\w+) -> if \(dark\) (\w+) else (\w+)/g)].map(([, entry, dark, light]) => {
    const id = ids.get(entry!);
    if (!id) throw new Error(`No id for ColorTheme.${entry}`);
    return { id, light: light!, dark: dark! };
  });
}

/** Light and dark status colors; `noDate` refers to a scheme role (`LightColors.onSurfaceVariant`). */
export function parseStatus(statusKt: string, schemes: Record<string, Scheme>): Record<'light' | 'dark', Scheme> {
  const read = (name: string): Scheme => {
    const body = statusKt.match(new RegExp(`val ${name} =\\s*StatusColors\\(([\\s\\S]*?)\\n\\s*\\)`))?.[1];
    if (!body) throw new Error(`No ${name}`);
    const colors: Scheme = {};
    for (const [, tone, argb, ref, role] of body.matchAll(
      /(\w+) = (?:Color\(0x[0-9A-Fa-f]{2}([0-9A-Fa-f]{6})\)|(\w+)\.(\w+))/g,
    )) {
      colors[tone!] = argb ? `#${argb.toLowerCase()}` : schemes[ref!]![role!]!;
    }
    return colors;
  };
  return { light: read('LightStatusColors'), dark: read('DarkStatusColors') };
}

export function render(): string {
  const read = (file: string) => readFileSync(new URL(file, THEME_DIR), 'utf8');
  const schemes = { ...parseSchemes(read('Color.kt')), ...parseSchemes(read('PresetColors.kt')) };
  const themes = parseThemes(read('Theme.kt'));
  const status = parseStatus(read('StatusColors.kt'), schemes);
  const byId = Object.fromEntries(
    themes.map(({ id, light, dark }) => {
      if (!schemes[light] || !schemes[dark]) throw new Error(`Missing scheme for ${id}`);
      return [id, { light: schemes[light], dark: schemes[dark] }];
    }),
  );
  return [
    '// Generated by scripts/gen-theme.ts from the Android theme (Color.kt, PresetColors.kt, StatusColors.kt).',
    '// Do not edit: change the Kotlin theme and run `npm run gen`.',
    '',
    `export const THEME_IDS = ${JSON.stringify(themes.map((t) => t.id))} as const;`,
    '',
    `export const SCHEMES = ${JSON.stringify(byId, null, 2)} as const;`,
    '',
    `export const STATUS_COLORS = ${JSON.stringify(status, null, 2)} as const;`,
    '',
  ].join('\n');
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(OUT, render());
  console.log(`Wrote ${fileURLToPath(OUT)}`);
}
