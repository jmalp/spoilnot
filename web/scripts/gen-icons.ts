// Generates src/ui/icons.generated.ts (DESIGN 18.2): the Material Icons used by the web app, as SVG markup from
// @material-design-icons/svg, the same glyphs as Compose's Icons.Rounded and Icons.Outlined. The names are listed in
// icons.txt as `variant/name`. Also writes public/icons/*.svg from the Android launcher icon; scripts/gen-app-icons.ts
// renders the PNGs from them. Run with `npm run gen`; CI checks the output is current.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const LIST = new URL('../icons.txt', import.meta.url);
const PACKAGE = new URL('../node_modules/@material-design-icons/svg/', import.meta.url);
const OUT = new URL('../src/ui/icons.generated.ts', import.meta.url);
const RES = new URL('../../app/src/main/res/', import.meta.url);
const PUBLIC_ICONS = new URL('../public/icons/', import.meta.url);

/** The markup inside an icon's <svg> element (its paths and shapes on a 24 by 24 grid). */
export function innerSvg(svg: string): string {
  const inner = svg.match(/<svg[^>]*viewBox="0 0 24 24"[^>]*>([\s\S]*)<\/svg>/)?.[1];
  if (!inner) throw new Error('Not a 24 by 24 icon');
  return inner.trim();
}

export function names(list: string): string[] {
  const all = list
    .split('\n')
    .map((line) => line.replace(/#.*/, '').trim())
    .filter(Boolean);
  for (const name of all) {
    if (!/^(round|outlined)\/[a-z0-9_]+$/.test(name)) throw new Error(`Bad icon name ${name}`);
  }
  return [...new Set(all)].sort();
}

/**
 * The launcher icon (an Android adaptive icon on a 108 by 108 canvas) as SVG: [crop] keeps the 72 by 72 part a
 * launcher shows, for iOS and browsers; without it the whole canvas, for Android's maskable icons.
 */
export function launcherSvg(foregroundXml: string, colorsXml: string, crop: boolean): string {
  const color = (name: string) => {
    const argb = colorsXml.match(new RegExp(`<color name="${name}">#[0-9A-Fa-f]{2}([0-9A-Fa-f]{6})</color>`))?.[1];
    if (!argb) throw new Error(`No color ${name}`);
    return `#${argb.toLowerCase()}`;
  };
  const paths = [...foregroundXml.matchAll(/<path([\s\S]*?)\/>/g)].map(([, attributes]) => {
    const d = attributes!.match(/android:pathData="([^"]+)"/)?.[1];
    const evenOdd = attributes!.includes('android:fillType="evenOdd"');
    return `<path fill="${color('ic_launcher_foreground')}"${evenOdd ? ' fill-rule="evenodd"' : ''} d="${d}"/>`;
  });
  const viewBox = crop ? '18 18 72 72' : '0 0 108 108';
  return [
    `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${viewBox}">`,
    `<rect width="108" height="108" fill="${color('ic_launcher_background')}"/>`,
    ...paths,
    '</svg>',
    '',
  ].join('\n');
}

/** The monochrome launcher icon's paths on its 108 by 108 canvas, for the welcome screen (WelcomeScreen). */
export function monochromePaths(xml: string): { d: string; evenOdd: boolean }[] {
  return [...xml.matchAll(/<path([\s\S]*?)\/>/g)].map(([, attributes]) => ({
    d: attributes!.match(/android:pathData="([^"]+)"/)![1]!,
    evenOdd: attributes!.includes('android:fillType="evenOdd"'),
  }));
}

export function render(): string {
  const monochrome = monochromePaths(readFileSync(new URL('drawable/ic_launcher_monochrome.xml', RES), 'utf8'));
  const icons = names(readFileSync(LIST, 'utf8')).map((name) => {
    const svg = readFileSync(new URL(`${name}.svg`, PACKAGE), 'utf8');
    return `  ${JSON.stringify(name)}: ${JSON.stringify(innerSvg(svg))},`;
  });
  return [
    '// Generated by scripts/gen-icons.ts from @material-design-icons/svg (Apache 2.0) and icons.txt. Do not edit.',
    '',
    'export const ICONS = {',
    ...icons,
    '} as const;',
    '',
    'export type IconName = keyof typeof ICONS;',
    '',
    '/** The launcher icon without its background, on a 108 by 108 canvas (ic_launcher_monochrome). */',
    `export const LAUNCHER_MONOCHROME = ${JSON.stringify(monochrome)} as const;`,
    '',
  ].join('\n');
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(OUT, render());
  const foreground = readFileSync(new URL('drawable/ic_launcher_foreground.xml', RES), 'utf8');
  const colors = readFileSync(new URL('values/colors.xml', RES), 'utf8');
  writeFileSync(new URL('icon.svg', PUBLIC_ICONS), launcherSvg(foreground, colors, true));
  writeFileSync(new URL('maskable.svg', PUBLIC_ICONS), launcherSvg(foreground, colors, false));
  console.log(`Wrote ${fileURLToPath(OUT)} and public/icons/*.svg`);
}
