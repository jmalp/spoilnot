// Generates src/strings.generated.ts from the Android app's strings.xml and the web-only strings-web.xml (DESIGN
// 18.2), so both apps use the same words. Run with `npm run gen`; CI checks the output is current.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const ANDROID = new URL('../../app/src/main/res/values/strings.xml', import.meta.url);
const WEB = new URL('../strings-web.xml', import.meta.url);
const OUT = new URL('../src/strings.generated.ts', import.meta.url);

export type Plural = Partial<Record<Intl.LDMLPluralRule, string>>;

/** Android string resource text to plain text: escapes (\' \" \n \\ \@ \?) and XML entities. */
export function unescape(raw: string): string {
  return raw
    .replace(/&lt;/g, '<')
    .replace(/&gt;/g, '>')
    .replace(/&quot;/g, '"')
    .replace(/&apos;/g, "'")
    .replace(/&#(\d+);/g, (_, code: string) => String.fromCodePoint(Number(code)))
    .replace(/&amp;/g, '&')
    .replace(/\\(.)/g, (_, c: string) => (c === 'n' ? '\n' : c === 't' ? '\t' : c));
}

export function parse(xml: string): { strings: Record<string, string>; plurals: Record<string, Plural> } {
  const body = xml.replace(/<!--[\s\S]*?-->/g, '');
  const strings: Record<string, string> = {};
  for (const [, name, text] of body.matchAll(/<string name="(\w+)"[^>]*>([\s\S]*?)<\/string>/g)) {
    strings[name!] = unescape(text!);
  }
  const plurals: Record<string, Plural> = {};
  for (const [, name, items] of body.matchAll(/<plurals name="(\w+)"[^>]*>([\s\S]*?)<\/plurals>/g)) {
    const forms: Plural = {};
    for (const [, quantity, text] of items!.matchAll(/<item quantity="(\w+)">([\s\S]*?)<\/item>/g)) {
      forms[quantity as Intl.LDMLPluralRule] = unescape(text!);
    }
    plurals[name!] = forms;
  }
  return { strings, plurals };
}

export function render(): string {
  const android = parse(readFileSync(ANDROID, 'utf8'));
  const web = parse(readFileSync(WEB, 'utf8'));
  for (const name of [...Object.keys(web.strings), ...Object.keys(web.plurals)]) {
    if (name in android.strings || name in android.plurals) throw new Error(`${name} is already in strings.xml`);
  }
  const strings = { ...android.strings, ...web.strings };
  const plurals = { ...android.plurals, ...web.plurals };
  return [
    '// Generated by scripts/gen-strings.ts from app/src/main/res/values/strings.xml and strings-web.xml.',
    '// Do not edit: change the XML and run `npm run gen`.',
    '',
    `export const STRINGS = ${JSON.stringify(strings, null, 2)} as const;`,
    '',
    `export const PLURALS = ${JSON.stringify(plurals, null, 2)} as const;`,
    '',
  ].join('\n');
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(OUT, render());
  console.log(`Wrote ${fileURLToPath(OUT)}`);
}
