// Generates app/src/main/kotlin/com/parcha/spoilnot/core/designsystem/theme/PresetColors.kt from themes.json
// (DESIGN 6.4, preset color themes). Each preset names four colors of its palette: the main color (buttons), a
// second one, an accent (also the "thrown away" color in charts) and the neutral that tints backgrounds. Material
// Color Utilities builds full light and dark schemes from them with the "fidelity" variant, which keeps each color
// close to the palette and picks tones that meet contrast (checked by ColorThemesContrastTest).
//
//   cd tools/themes && npm ci && npm run generate
import { readFileSync, writeFileSync } from 'node:fs';
import {
  argbFromHex, DynamicScheme, Hct, hexFromArgb, MaterialDynamicColors as M, TonalPalette,
} from '@material/material-color-utilities';

// 0.3.0 does not export the Variant enum from its entry point; FIDELITY is 5 (dynamiccolor/variant.js).
const FIDELITY = 5;
const ROLES = [
  'primary', 'onPrimary', 'primaryContainer', 'onPrimaryContainer', 'inversePrimary',
  'secondary', 'onSecondary', 'secondaryContainer', 'onSecondaryContainer',
  'tertiary', 'onTertiary', 'tertiaryContainer', 'onTertiaryContainer',
  'background', 'onBackground', 'surface', 'onSurface', 'surfaceVariant', 'onSurfaceVariant', 'surfaceTint',
  'inverseSurface', 'inverseOnSurface', 'error', 'onError', 'errorContainer', 'onErrorContainer',
  'outline', 'outlineVariant', 'scrim', 'surfaceBright', 'surfaceContainer', 'surfaceContainerHigh',
  'surfaceContainerHighest', 'surfaceContainerLow', 'surfaceContainerLowest', 'surfaceDim',
];

const themes = JSON.parse(readFileSync(new URL('./themes.json', import.meta.url), 'utf8'));
const out = new URL(process.argv[2] ?? '../../app/src/main/kotlin/com/parcha/spoilnot/core/designsystem/theme/PresetColors.kt', import.meta.url);

// Backgrounds take the neutral's hue with a visible but quiet tint (Material's vibrant schemes use about 10).
const NEUTRAL_CHROMA = 10;
const NEUTRAL_VARIANT_CHROMA = 14;

function scheme({ main, second, accent, neutral }, isDark) {
  const tint = Hct.fromInt(argbFromHex(neutral));
  return new DynamicScheme({
    sourceColorArgb: argbFromHex(main),
    variant: FIDELITY,
    contrastLevel: 0,
    isDark,
    primaryPalette: TonalPalette.fromInt(argbFromHex(main)),
    secondaryPalette: TonalPalette.fromInt(argbFromHex(second)),
    tertiaryPalette: TonalPalette.fromInt(argbFromHex(accent)),
    neutralPalette: TonalPalette.fromHueAndChroma(tint.hue, Math.min(tint.chroma, NEUTRAL_CHROMA)),
    neutralVariantPalette: TonalPalette.fromHueAndChroma(tint.hue, Math.min(tint.chroma, NEUTRAL_VARIANT_CHROMA)),
  });
}

function kotlinScheme(name, s, isDark) {
  const lines = ROLES.map((role) => {
    const argb = M[role].getArgb(s) >>> 0;
    return `        ${role} = Color(0x${argb.toString(16).toUpperCase().padStart(8, '0')}),`;
  });
  return `internal val ${name} =\n    ${isDark ? 'darkColorScheme' : 'lightColorScheme'}(\n${lines.join('\n')}\n    )\n`;
}

let kt = `package com.parcha.spoilnot.core.designsystem.theme

import androidx.compose.material3.darkColorScheme
import androidx.compose.material3.lightColorScheme
import androidx.compose.ui.graphics.Color

// Generated by tools/themes/generate-themes.mjs from tools/themes/themes.json (Material Color Utilities 0.3.0,
// fidelity variant). Do not edit by hand; change themes.json and regenerate.
`;
for (const t of themes) {
  const id = t.id.charAt(0).toUpperCase() + t.id.slice(1);
  kt += `\n// ${t.name}: main #${t.main}, second #${t.second}, accent #${t.accent}, neutral #${t.neutral} (palette ${t.palette.join(' ')})\n`;
  kt += kotlinScheme(`${id}Light`, scheme(t, false), false);
  kt += '\n' + kotlinScheme(`${id}Dark`, scheme(t, true), true);
}
writeFileSync(out, kt);
console.log(`wrote ${themes.length} themes to ${out.pathname}`);
for (const t of themes) {
  const l = scheme(t, false); const d = scheme(t, true);
  console.log(t.id.padEnd(12), 'light primary', hexFromArgb(M.primary.getArgb(l)), 'container', hexFromArgb(M.primaryContainer.getArgb(l)), '| dark primary', hexFromArgb(M.primary.getArgb(d)));
}
